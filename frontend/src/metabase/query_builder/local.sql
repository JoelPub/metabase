SELECT "source"."距离（周）" AS "距离（周）",
       count(*) AS "count"
FROM
  (SELECT "PUBLIC"."ORDERS"."CREATED_AT" AS "CREATED_AT",
          CASE
              WHEN "PUBLIC"."ORDERS"."CREATED_AT" > TIMESTAMP WITH TIME ZONE '2019-04-01 00:00:00.000+08:00' THEN '1'
              WHEN "PUBLIC"."ORDERS"."CREATED_AT" > TIMESTAMP WITH TIME ZONE '2019-03-01 00:00:00.000+08:00' THEN '0'
              WHEN "PUBLIC"."ORDERS"."CREATED_AT" > TIMESTAMP WITH TIME ZONE '2019-02-01 00:00:00.000+08:00' THEN '-1'
              ELSE '-99'
          END AS "距离（周）"
   FROM "PUBLIC"."ORDERS") "source"
WHERE ("source"."CREATED_AT" >= TIMESTAMP WITH TIME ZONE '2019-02-01 00:00:00.000+08:00'
       AND "source"."CREATED_AT" < TIMESTAMP WITH TIME ZONE '2019-05-01 00:00:00.000+08:00'
       AND ("source"."距离（周）" <> '-99'
            OR "source"."距离（周）" IS NULL))
GROUP BY "source"."距离（周）"
ORDER BY "source"."距离（周）" ASC